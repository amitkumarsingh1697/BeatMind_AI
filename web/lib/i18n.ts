const TEXT: Record<Locale, AppText> = { en, hi };

export function appText(locale: Locale): AppText {
  return TEXT[locale] ?? en;
}

/**
 * The message for an API problem. English uses the API's own detail (it can be more specific);
 * Hindi uses the translated text for known codes and falls back to the API's English.
 */
export function errorText(locale: Locale, p: { detail: string; code: string | null }): string {
  const known = p.code ? appText(locale).errors[p.code] : undefined;
  if (locale === "en") return p.detail || known || "Something went wrong.";
  return known ?? p.detail;
}

/** Every leaf string of a dictionary, for the tests (no empty strings, no copyright promises). */
export function allStrings(value: unknown, out: string[] = []): string[] {
  if (typeof value === "string") out.push(value);
  else if (typeof value === "function") {
    const fn = value as (...args: unknown[]) => unknown;
    const r = fn(1, 2, "x");
    if (typeof r === "string") out.push(r);
  } else if (Array.isArray(value)) value.forEach((v) => allStrings(v, out));
  else if (value && typeof value === "object") Object.values(value).forEach((v) => allStrings(v, out));
  return out;
}

